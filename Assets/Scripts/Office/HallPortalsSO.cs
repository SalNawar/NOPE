using UnityEngine;

/// <summary>
/// The hall's portal rings, the one source of where they are (HALL-FX,
/// BUG-73d: the openings used to live in DeskConfigSO and in three tools):
/// the drawing they are painted in, each ring's layers and its opening, and
/// the painted-aperture masks the vortex is clipped by (BUG-26a: the hole each
/// ring's metal encloses, what stands in front of it and what is seen through
/// the bay's glass, read from the painting by tools/hall/portal_masks.py,
/// never by a colour test at run time). One asset,
/// Assets/Data/Config/HallPortals.asset: Build Office UI hands it to every
/// PortalEffect, AnimeHallPortalLink places and opens the vortexes from it.
/// The openings and masks are regenerated by the tool, never hand-edited
/// (HallPortalsTests re-fits the masks and checks the openings against them).
/// </summary>
[CreateAssetMenu(menuName = "TimeDesk/Hall Portals", fileName = "HallPortals")]
public sealed class HallPortalsSO : ScriptableObject
{
    /// <summary>The hall drawing the rings are painted in (its id in the hall's AnimeHallPresentation); without it each vortex falls back on its ring layer's opaque rect, unmasked.</summary>
    public string drawing = "62 Approved deeper architecture";

    /// <summary>The drawing's canvas (its source painting's pixels): the space of every opening and mask crop, whatever size the drawing is imported at.</summary>
    public Vector2 canvas = new Vector2(2172f, 724f);

    /// <summary>The painted-aperture masks (HallPortalMasks.png, linear): one crop per ring; R the hole, G an occluder in front of it, B seen through the bay's glass, A the depth inside the hole's edge (the rim).</summary>
    public Texture2D masks;

    /// <summary>Each portal's ring, in the order of the gameplay's effects (Build Office UI makes one PortalEffect per entry).</summary>
    public HallPortalRing[] rings = new HallPortalRing[0];

    /// <summary>The vortex of an open departure ring (cyan) and of the Return Gate (amber), and how they move.</summary>
    public PortalVortexTuning vortex = new PortalVortexTuning();

    /// <summary>A departure's flare: seconds, up and down (with reduced motion: one step up, then down at its end).</summary>
    [Min(0.05f)] public float pulseSeconds = 0.8f;
}

/// <summary>One portal ring in the hall (HallPortalsSO.rings): its art layers by their AnimeHallPresentation ids, and its opening and mask on the drawing's canvas.</summary>
[System.Serializable]
public sealed class HallPortalRing
{
    /// <summary>The portal's number (agency.portals[].number).</summary>
    public int portal;

    /// <summary>The secure bay's layer (the fallback draws the effect at its order less one).</summary>
    public string bay;

    /// <summary>The metal ring's layer: never tinted; without the drawing its opaque rect places the effect.</summary>
    public string ring;

    /// <summary>The painted glass's layer (listed so a renamed layer is one edit here; the warning names it when missing).</summary>
    public string glass;

    /// <summary>The ring's opening on the canvas (px, top-left origin): the centre (x, y) and radii (z across, w up) of the mask's hole by its moments (an ellipse's radii are twice its standard deviations). Written by tools/hall/portal_masks.py.</summary>
    public Vector4 opening;

    /// <summary>How far the hole reaches, in opening radii (at least 1 for a ring; more for an arch, whose hole is not an ellipse): the iris opens this far, so it uncovers the whole hole.</summary>
    public float reach = 1f;

    /// <summary>The ring's mask crop on the canvas (px, top-left origin).</summary>
    public Rect maskCanvas;

    /// <summary>The same crop in the mask atlas's texture coordinates (y up).</summary>
    public Rect maskRect;
}
