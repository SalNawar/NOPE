using UnityEngine;

/// <summary>
/// The hall's portal rings, the one source of where they are (HALL-FX,
/// BUG-73d: the openings used to live in DeskConfigSO and in three tools):
/// the drawing they are painted in, each ring's layers and its opening, and
/// the painted-aperture masks the vortex is clipped by (BUG-26a: the hole each
/// ring's metal encloses, what stands in front of it and what is seen through
/// the bay's glass, read from the painting by tools/hall/portal_masks.py,
/// never by a colour test at run time). One asset,
/// Assets/Data/Config/HallPortals.asset: Build Office UI hands it to every
/// PortalEffect, AnimeHallPortalLink places and opens the vortexes from it.
/// The openings and masks are regenerated by the tool, never hand-edited
/// (HallPortalsTests re-fits the masks and checks the openings against them);
/// the chevron ellipses and the gate's knobs (<see cref="gate"/>) are set by hand.
/// </summary>
[CreateAssetMenu(menuName = "TimeDesk/Hall Portals", fileName = "HallPortals")]
public sealed class HallPortalsSO : ScriptableObject
{
    /// <summary>The hall drawing the rings are painted in (its id in the hall's AnimeHallPresentation); without it each vortex falls back on its ring layer's opaque rect, unmasked.</summary>
    public string drawing = "62 Approved deeper architecture";

    /// <summary>The drawing's canvas (its source painting's pixels): the space of every opening and mask crop, whatever size the drawing is imported at.</summary>
    public Vector2 canvas = new Vector2(2172f, 724f);

    /// <summary>The painted-aperture masks (HallPortalMasks.png, linear): one crop per ring; R the hole, G an occluder in front of it, B seen through the bay's glass, A the depth inside the hole's edge (the rim).</summary>
    public Texture2D masks;

    /// <summary>Each portal's ring, in the order of the gameplay's effects (Build Office UI makes one PortalEffect per entry).</summary>
    public HallPortalRing[] rings = new HallPortalRing[0];

    /// <summary>The vortex of an open departure ring (cyan) and of the Return Gate (amber), and how they move.</summary>
    public PortalVortexTuning vortex = new PortalVortexTuning();

    /// <summary>The old swirl's flare at a send: seconds, up and down (with reduced motion: one step up, then down at its end). Read only while gate.eventHorizon is off; the event horizon's kawoosh takes gate.kawooshSeconds.</summary>
    [Min(0.05f)] public float pulseSeconds = 0.8f;

    /// <summary>The rings as gates (the night of 2026-11-07, DECISIONS D6): the chevrons, the event horizon, the kawoosh, the close.</summary>
    public PortalGateTuning gate = new PortalGateTuning();
}

/// <summary>
/// The hall rings as gates (HallPortalsSO.gate; PortalEffect, PortalGateTrack,
/// the shader TimeDesk/PortalGlow; DECISIONS D6, Saleh 2026-11-07: "portals",
/// the Stargate idea): offline a dark ring; locked in, the chevrons light one
/// by one over the calibration; open, a slow rippling event horizon in two cel
/// tones of the ring's light (HallLightingSO.portalOpenLight, the Return
/// Gate's returnGateLight) with a soft rim glow; a send, the kawoosh; closing,
/// a fade over HallLightingSO.portalFadeSeconds. Every knob is here; the
/// event horizon and the chevrons can be set back to the old swirl.
/// </summary>
[System.Serializable]
public sealed class PortalGateTuning
{
    [Header("The look")]
    /// <summary>True: an open ring shows the event horizon; false: the old cel swirl (HallPortalsSO.vortex), its flare at a send.</summary>
    public bool eventHorizon = true;

    /// <summary>True: a dialed ring shows its chevrons; false: none (the old look).</summary>
    public bool showChevrons = true;

    /// <summary>The ring's light colours when the hall has no HallLightingRig (with one, its HallLightingSO.portalOpenLight and returnGateLight): a departure ring's and the Return Gate's.</summary>
    public Color departureTone = new Color(0.35f, 0.85f, 1f), returnTone = new Color(1f, 0.62f, 0.25f);

    [Header("The event horizon (open)")]
    /// <summary>The event horizon's dark tone as a share of the ring's light colour (its light tone is the colour itself, lifted toward white by poolLift).</summary>
    [Range(0.1f, 1f)] public float poolDark = 0.7f;

    /// <summary>How far the light tone is lifted toward white.</summary>
    [Range(0f, 1f)] public float poolLift = 0.25f;

    /// <summary>How many ripple bands cross the event horizon from its centre to its rim.</summary>
    [Range(1f, 8f)] public float rippleRings = 2.6f;

    /// <summary>How much of each ripple band is the light tone (the rest the dark one): thin light crests on the dark water.</summary>
    [Range(0.1f, 0.9f)] public float rippleShare = 0.28f;

    /// <summary>The light disc at the event horizon's centre (opening radii).</summary>
    [Range(0f, 0.6f)] public float poolCore = 0.18f;

    /// <summary>How fast the ripples run out to the rim (bands a second; under 1 Hz, so the flicker check stays green; still with reduced motion).</summary>
    [Range(0f, 1f)] public float rippleHz = 0.15f;

    /// <summary>How far the ripples wander off round (bands), and how fast (a second; still with reduced motion).</summary>
    [Range(0f, 1f)] public float wobble = 0.45f, wobbleHz = 0.1f;

    /// <summary>The soft rim glow's strength inside the hole's painted edge.</summary>
    [Range(0f, 1f)] public float rimGlow = 0.55f;

    /// <summary>Seconds the event horizon takes to open (an eased iris, no overshoot; at once with reduced motion).</summary>
    [Min(0f)] public float openSeconds = 0.7f;

    /// <summary>Seconds the event horizon and the chevrons take to fade out when the hall has no HallLightingRig (with one, its HallLightingSO.portalFadeSeconds).</summary>
    [Min(0f)] public float fadeSeconds = 0.8f;

    [Header("The kawoosh (a send)")]
    /// <summary>Seconds a kawoosh takes: its burst out (to the peak and half back) then its settle into the event horizon (1.2: 36 frames at 30 fps).</summary>
    [Min(0.05f)] public float kawooshSeconds = 1.2f;

    /// <summary>Where the kawoosh peaks, as a share of its time (0.36: 0.43 s, frame 13 at 30 fps).</summary>
    [Range(0.1f, 0.9f)] public float kawooshPeak = 0.36f;

    /// <summary>How far the plume reaches out at its peak (opening radii, from a fifth at its start).</summary>
    [Range(0.5f, 1.5f)] public float kawooshReach = 1.15f;

    /// <summary>How much brighter the ring reads at the kawoosh's peak (the bloom flares round the ring).</summary>
    [Range(0f, 2f)] public float kawooshFlare = 0.7f;

    /// <summary>The kawoosh's sound (the cue portal_kawoosh, or its placeholder) volume.</summary>
    [Range(0f, 1f)] public float kawooshVolume = 0.7f;

    /// <summary>The least seconds between two of a ring's changes (a chevron, the opening, a kawoosh): a send waits for it (one change per 2 s at most).</summary>
    [Min(0f)] public float dwellSeconds = 2f;

    [Header("The chevrons (locked in)")]
    /// <summary>How many chevrons a ring has: one lights per calibration time / chevrons, the first at the lock-in.</summary>
    [Range(1, 9)] public int chevrons = 7;

    /// <summary>Degrees between a ring's chevron sites when its HallPortalRing.chevronStep is 0 (40: the Stargate's nine sites).</summary>
    [Range(10f, 60f)] public float chevronStep = 40f;

    /// <summary>The chevron ellipse as a share of the opening when a ring has none (HallPortalRing.chevrons).</summary>
    [Range(1f, 1.5f)] public float chevronGrow = 1.22f;

    /// <summary>A chevron's half-width as a share of the ring's mean opening radius when a ring has none (HallPortalRing.chevronSize).</summary>
    [Range(0.05f, 0.3f)] public float chevronSize = 0.14f;

    /// <summary>A lit chevron's colour (the Stargate's amber) and an unlit one's.</summary>
    public Color chevronLit = new Color(1f, 0.6f, 0.2f), chevronDark = new Color(0.3f, 0.27f, 0.3f);
}

/// <summary>One portal ring in the hall (HallPortalsSO.rings): its art layers by their AnimeHallPresentation ids, and its opening and mask on the drawing's canvas.</summary>
[System.Serializable]
public sealed class HallPortalRing
{
    /// <summary>The portal's number (agency.portals[].number).</summary>
    public int portal;

    /// <summary>The secure bay's layer (the fallback draws the effect at its order less one).</summary>
    public string bay;

    /// <summary>The metal ring's layer: never tinted; without the drawing its opaque rect places the effect.</summary>
    public string ring;

    /// <summary>The painted glass's layer (listed so a renamed layer is one edit here; the warning names it when missing).</summary>
    public string glass;

    /// <summary>The ring's opening on the canvas (px, top-left origin): the centre (x, y) and radii (z across, w up) of the mask's hole by its moments (an ellipse's radii are twice its standard deviations). Written by tools/hall/portal_masks.py.</summary>
    public Vector4 opening;

    /// <summary>How far the hole reaches, in opening radii (at least 1 for a ring; more for an arch, whose hole is not an ellipse): the iris opens this far, so it uncovers the whole hole.</summary>
    public float reach = 1f;

    /// <summary>The ring's mask crop on the canvas (px, top-left origin).</summary>
    public Rect maskCanvas;

    /// <summary>The same crop in the mask atlas's texture coordinates (y up).</summary>
    public Rect maskRect;

    /// <summary>The ellipse its chevrons sit on: the middle of its metal band on the canvas (px, top-left origin: centre x, y and radii z across, w up), read by eye on the painting (the night of 2026-11-07); zero radii: the opening grown by HallPortalsSO.gate.chevronGrow.</summary>
    public Vector4 chevrons;

    /// <summary>Degrees between its chevron sites (0: HallPortalsSO.gate.chevronStep): 40 on a full ring, less on an arch, so its seven fit over the top.</summary>
    public float chevronStep;

    /// <summary>A chevron's half-width on the canvas (px; 0: HallPortalsSO.gate.chevronSize of the mean opening radius).</summary>
    public float chevronSize;
}
