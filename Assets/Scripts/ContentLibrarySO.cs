    /// <summary>Cached lookup: culture id ("neutral" or a nation id) -> theme.</summary>
    private Dictionary<string, ThemeSO> _themeById;

    /// <summary>Cached lookup: language -> UI string table.</summary>
    private Dictionary<string, UiStringTableSO> _tableByLanguage;

    /// <summary>
    /// Clears cached lookups when the asset is loaded/reloaded.
    /// This prevents stale dictionaries after domain reloads.
    /// </summary>
    private void OnEnable() => ResetLookups();

    /// <summary>
    /// Clears cached lookups when the asset changes in the editor (an
    /// inspector edit, or Generate World rewiring its arrays), so lookups in
    /// the same editor session never read the old arrays.
    /// </summary>
    private void OnValidate() => ResetLookups();

    /// <summary>Drops every cached lookup; the next lookup rebuilds them (EnsureLookups).</summary>
    private void ResetLookups()
    {
        _eraById = null;
        _effectByName = null;
        _upgradeById = null;
        _endingById = null;
        _nationById = null;
        _profileById = null;
        _themeById = null;
        _tableByLanguage = null;
    }

    /// <summary>
    /// Returns an Era by its string ID (e.g., "rome").
    /// Useful for saves or ID-based references.
    /// </summary>
    public EraSO GetEraById(string id)
    {
        if (string.IsNullOrWhiteSpace(id))
            return null;

        EnsureLookups();
        return _eraById.TryGetValue(id, out EraSO era) ? era : null;
    }

