    /// <summary>
    /// The DayPlan a day uses (DayPlans.Pick): the plan with that day number,
    /// else the latest earlier one, else null. Days after the last authored
    /// plan reuse it (the Future stays open once a leader exists).
    /// </summary>
    public DayPlanSO GetDayPlan(int dayNumber)
    {
        if (dayPlans == null)
            return null;

        DayPlanSO[] plans = dayPlans.Where(p => p != null).ToArray();
        int index = global::DayPlans.Pick(plans.Select(p => p.DayNumber).ToArray(), dayNumber);
        return index >= 0 ? plans[index] : null;
    }

    /// <summary>
    /// Builds internal dictionaries the first time they are needed.
    /// </summary>
    private void EnsureLookups()
    {
        if (_eraById != null)
            return;

        _eraById = new Dictionary<string, EraSO>(StringComparer.OrdinalIgnoreCase);
        _effectByName = new Dictionary<string, EffectSO>(StringComparer.OrdinalIgnoreCase);
        _upgradeById = new Dictionary<string, UpgradeSO>(StringComparer.OrdinalIgnoreCase);
        _endingById = new Dictionary<string, EndingSO>(StringComparer.OrdinalIgnoreCase);
        _nationById = new Dictionary<string, NationSO>(StringComparer.OrdinalIgnoreCase);
        _profileById = new Dictionary<string, NationEraProfileSO>(StringComparer.OrdinalIgnoreCase);
        _themeById = new Dictionary<string, ThemeSO>(StringComparer.OrdinalIgnoreCase);
        _tableByLanguage = new Dictionary<string, UiStringTableSO>(StringComparer.Ordinal);

        foreach (ThemeSO t in Themes.Prepend(neutralTheme))
            if (t != null && !string.IsNullOrWhiteSpace(t.cultureId))
                _themeById.TryAdd(t.cultureId, t);

        foreach (UiStringTableSO table in StringTables)
            if (table != null && !string.IsNullOrWhiteSpace(table.language))
                _tableByLanguage.TryAdd(table.language, table);

        if (nations != null)
            foreach (NationSO n in nations)
                if (n != null && !string.IsNullOrWhiteSpace(n.id))
                    _nationById.TryAdd(n.id, n);

        if (nationEraProfiles != null)
            foreach (NationEraProfileSO p in nationEraProfiles)
                if (p != null && !string.IsNullOrWhiteSpace(p.id))
                    _profileById.TryAdd(p.id, p);

        if (eras != null)
        {
            foreach (EraSO e in eras)
            {
                if (e == null || string.IsNullOrWhiteSpace(e.id))
                    continue;

                _eraById.TryAdd(e.id, e);
            }
        }

        if (effects != null)
        {
            foreach (EffectSO fx in effects)
            {
                if (fx == null)
                    continue;

                _effectByName.TryAdd(fx.name, fx);
            }
        }

        if (upgrades != null)
        {
            foreach (UpgradeSO u in upgrades)
            {
                if (u == null || string.IsNullOrWhiteSpace(u.id))
                    continue;

                _upgradeById.TryAdd(u.id, u);
            }
        }

        if (endings != null)
        {
            foreach (EndingSO e in endings)
            {
                if (e == null || string.IsNullOrWhiteSpace(e.id))
                    continue;

                _endingById.TryAdd(e.id, e);
            }
        }
    }
