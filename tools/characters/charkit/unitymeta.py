def _write(path, text):
    if os.path.exists(path):
        return False
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True


def texture_meta(png_path, height, feet_from_top):
    """Writes {png}.meta unless it exists. Returns True when written."""
    pivot_y = (height - feet_from_top) / float(height)
    # Unity writes floats with the shortest round-trip form of the float32 value.
    import numpy as np
    pivot = np.format_float_positional(np.float32(pivot_y), unique=True, trim="-")
    return _write(png_path + ".meta", TEXTURE.format(guid=uuid.uuid4().hex, pivot_y=pivot, ppu=height))


def folder_meta(folder):
    """Writes {folder}.meta unless it exists. Returns True when written."""
    return _write(folder.rstrip("/\\") + ".meta", FOLDER.format(guid=uuid.uuid4().hex))
